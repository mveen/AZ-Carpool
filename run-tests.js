// run-tests.js — `npm test`. Runs every *.test.js in its own process, prints per-file results and a total,
// and enforces the rule "a changed module needs a changed test file" (see README, tests.lock.json).
//
//   npm test            run everything and check the rule
//   npm run lock        run everything; if green, remember the current module + test versions as the new baseline
//                       and write the exact number of tests to test-count.js (shown in the help)
import { spawn, spawnSync } from 'node:child_process';
import { availableParallelism } from 'node:os';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.dirname(fileURLToPath(import.meta.url));
const LOCK = path.join(dir, 'tests.lock.json');
// Files that are tooling, not app modules.
const NOT_MODULES = new Set(['fake-db.js', 'run-tests.js', 'firebase-config.js', 'service-worker.js', 'i18n-codemod.mjs']);
// A module whose tests live in another module's test file.
const TEST_FOR = { 'texts-nl.js': 'i18n.test.js', 'help-nl.js': 'help.test.js' };

const TESTS = path.join(dir, 'tests');
const files = readdirSync(dir);
const testFiles = readdirSync(TESTS).filter(f => f.endsWith('.test.js')).sort();
const modules = files.filter(f => f.endsWith('.js') && !f.endsWith('.test.js') && !f.startsWith('test-') && !NOT_MODULES.has(f)).sort();
const testOf = m => TEST_FOR[m] || m.replace(/\.js$/, '.test.js');
const hash = f => createHash('sha256').update(readFileSync(path.join(f.endsWith('.test.js') ? TESTS : dir, f))).digest('hex');
const lockNow = () => Object.fromEntries(modules.map(m => [m, { module: hash(m), test: existsSync(path.join(TESTS, testOf(m))) ? hash(testOf(m)) : null }]));

const LOCKING = process.argv.includes('--lock');
// Without rsync, tests/deploy-rsync.test.js and tests/deploy-test-env.test.js skip 9 tests, so this machine counts fewer tests than CI. A count
// made here would then be wrong in test-count.js (and fail in CI), so: no lock without rsync, and no count check either (it would be a false alarm).
const HAVE_RSYNC = spawnSync('rsync', ['--version'], { stdio: 'ignore' }).status === 0;
const COUNT_FILE = path.join(dir, 'test-count.js');
const countFileSource = n => `// Generated by \`npm run lock\` (run-tests.js). Do not edit by hand. The help ("Over deze app") shows this number.\nexport const TEST_COUNT = ${n};\n`;
if (LOCKING) {
  if (!HAVE_RSYNC) { console.error('Cannot lock: rsync is not installed, so 9 upload tests are skipped and the test count would be 9 too low (CI would fail on it).\nInstall rsync (Linux: apt-get install -y rsync; Mac: it is there already) and run again.'); process.exit(1); }
  const missing = modules.filter(m => !testFiles.includes(testOf(m)));
  if (missing.length) { console.error('Cannot lock: no test file for', missing.join(', ')); process.exit(1); }
}

let failedFiles = 0, totalPassed = 0, totalFailed = 0;
console.log('Running', testFiles.length, 'test files\n');

// Every test file is its own process and shares nothing with the others (own temp folders, no fixed ports), so they run side by side.
// TEST_JOBS=1 runs them one by one (to hunt a suspected interference); the default is the number of cores, at most 4.
const JOBS = Math.max(1, Number(process.env.TEST_JOBS) || Math.min(4, availableParallelism()));
const runFile = f => new Promise(resolve => {
  const child = spawn(process.execPath, [f], { cwd: TESTS, env: { ...process.env, TZ: 'Europe/Amsterdam' } });
  let out = '', timedOut = false;
  const timer = setTimeout(() => { timedOut = true; child.kill('SIGKILL'); }, 120000);
  child.stdout.on('data', d => { out += d; }); child.stderr.on('data', d => { out += d; });
  child.on('close', status => { clearTimeout(timer); resolve({ f, out, status: timedOut ? null : status }); });
  child.on('error', e => { clearTimeout(timer); resolve({ f, out: String(e), status: null }); });
});
const results = new Array(testFiles.length);
let next = 0;
await Promise.all(Array.from({ length: Math.min(JOBS, testFiles.length) }, async () => {
  while (next < testFiles.length) { const i = next++; results[i] = await runFile(testFiles[i]); }
}));

// Printed in file order, so the output is the same on every run.
for (const { f, out, status } of results) {
  const m = out.match(/(\d+) passed, (\d+) failed/g);
  const last = m ? m[m.length - 1].match(/(\d+) passed, (\d+) failed/) : null;
  const p = last ? +last[1] : 0, x = last ? +last[2] : 0;
  // The count must be the LAST thing a test file prints: a test written below the summary line would run but not count, and could fail unseen.
  const summaryLast = /\d+ passed, \d+ failed\s*$/.test(out);
  const ok = status === 0 && last && x === 0 && summaryLast;
  totalPassed += p; totalFailed += x;
  if (!ok) { failedFiles++; if (!last) totalFailed++; }
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${f.padEnd(28)} ${last ? `${p} passed, ${x} failed` : 'did not finish (crash or timeout)'}`);
  if (last && !summaryLast) console.log('      the "N passed, M failed" line is not the last line: move it to the end of the file');
  if (!ok) console.log(out.split('\n').filter(l => /✗|Error|error/.test(l) || l.startsWith('     ')).slice(0, 30).map(l => '      ' + l).join('\n'));
}

if (LOCKING) {
  // Lock = run everything, and only when it is all green remember the baseline and the exact test count (shown in the help).
  if (failedFiles || totalFailed) { console.error('\nCannot lock: tests are not green.'); process.exit(1); }
  writeFileSync(LOCK, JSON.stringify(lockNow(), null, 2) + '\n');
  writeFileSync(COUNT_FILE, countFileSource(totalPassed));
  console.log(`\nLocked: tests.lock.json updated for ${modules.length} modules, test-count.js set to ${totalPassed} tests.`);
  process.exit(0);
}

// The rule: every module has a test file, and a changed module comes with a changed test file.
console.log('\nRule check: every module change needs a test change');
const problems = [];
const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, 'utf8')) : null;
const now = lockNow();
for (const m of modules) {
  if (!testFiles.includes(testOf(m))) { problems.push(`${m}: no test file (${testOf(m)})`); continue; }
  if (!lock) continue;
  const old = lock[m];
  if (!old) continue; // new module: it has a test file, which is what counts
  if (old.module !== now[m].module && old.test === now[m].test) problems.push(`${m} changed, but ${testOf(m)} did not. Add or update a test, then run: npm run lock`);
}
if (!lock) problems.push('tests.lock.json is missing. Run: npm run lock');
// The help shows the number of tests, so it must be the real number.
const shown = existsSync(COUNT_FILE) ? +(readFileSync(COUNT_FILE, 'utf8').match(/TEST_COUNT = (\d+)/) || [])[1] : NaN;
if (!HAVE_RSYNC) console.log('NOTE  rsync is not installed: 9 upload tests were skipped, so the test count in the help is not checked here (CI checks it)');
else if (shown !== totalPassed) problems.push(`test-count.js says ${shown}, but there are ${totalPassed} tests. Run: npm run lock`);
if (problems.length) problems.forEach(p => console.log('FAIL  ' + p)); else console.log('PASS  all modules covered' + (HAVE_RSYNC ? ', test count in help is correct' : ''));

console.log(`\nTotal: ${totalPassed} passed, ${totalFailed} failed, ${failedFiles} file(s) failing, ${problems.length} rule problem(s)`);
process.exit(failedFiles || problems.length ? 1 : 0);
